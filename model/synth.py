"""MIAT high-level synthesis: GRAFCET model (JSON) -> Python controller/datapath.

Fixed synthesis rules (no LLM involved):
  * one state variable X<id> per step; reset(): initial steps = 1, others = 0
  * grafcet_<G>(): evaluates the transitions of G in listing order and fires the
    first enabled one  (if X_src... and R: X_src = 0; X_dst = 1), then returns
    -> at most one transition per GRAFCET per tick (as in the original paper)
  * AND divergence: one transition with several destinations; AND convergence:
    one transition with several sources (all must be active)
  * datapath_<G>(): calls the bound action functions of every active step;
    inputs/outputs are wired exactly as declared by the IDEF0 ICOM binding
  * macro step (Sub-GRAFCET): its datapath runs datapath_<child>() then
    grafcet_<child>(); the child is reset when the macro step is (re)entered
  * TO<id> = time spent in step <id> exceeds its declared timeout (timer event)
  * a step flagged "blocking" (original paper's '=1' after a timed action) is
    emulated as a blocking call: its outgoing transitions wait for <step>_done
"""
import json, re, hashlib, sys, keyword

TOK = re.compile(r"\b([A-Za-z_][A-Za-z0-9_]*)\b")
PY_WORDS = {"and", "or", "not", "True", "False"}


def cond_to_py(cond: str, step_ids: set) -> str:
    c = cond.strip()
    if c in ("1", "True", "true"):
        return "True"
    def rep(m):
        w = m.group(1)
        if w in PY_WORDS:
            return w
        if re.fullmatch(r"X\w+", w) and w[1:] in step_ids:
            return f"S.X['{w[1:]}']"
        if re.fullmatch(r"TO\w+", w) and w[2:] in step_ids:
            return f"S.timeout('{w[2:]}', C.t)"
        return f"C.{w}"
    return TOK.sub(rep, c)


def synthesize(model: dict, src_name="model.json") -> str:
    g_by_id = {g["id"]: g for g in model["grafcets"]}
    all_steps = {}
    for g in model["grafcets"]:
        for s in g["steps"]:
            all_steps[s["id"]] = (g["id"], s)
    step_ids = set(all_steps)
    sha = hashlib.sha256(json.dumps(model, sort_keys=True).encode()).hexdigest()[:12]
    L = []
    w = L.append
    w(f'"""AUTO-GENERATED by model/synth.py from {src_name} (sha {sha}). DO NOT EDIT.')
    w("Change the GRAFCET model and re-synthesize instead (single source of truth).\"\"\"")
    w("from sim.api import Command")
    w("")
    w("class State:")
    w("    def __init__(self):")
    w(f"        self.X = {{{', '.join(repr(s)+': 0' for s in all_steps)}}}")
    w("        self.t_entry = {}")
    w(f"        self.TMO = {{{', '.join(repr(sid)+': '+repr(s.get('timeout')) for sid,(g,s) in all_steps.items() if s.get('timeout'))}}}")
    w("        self.trace = []")
    w("    def activate(self, sid, t):")
    w("        self.X[sid] = 1; self.t_entry[sid] = t")
    w("    def timeout(self, sid, t):")
    w("        return self.X[sid] == 1 and (t - self.t_entry.get(sid, t)) >= self.TMO[sid] - 1e-9")
    w("")
    # reset functions
    for g in model["grafcets"]:
        w(f"def reset_{g['id']}(S, t):")
        for s in g["steps"]:
            w(f"    S.X['{s['id']}'] = 0")
        for i in g["initial"]:
            w(f"    S.activate('{i}', t)")
        # children reset too
        for s in g["steps"]:
            if s.get("macro"):
                w(f"    reset_{s['macro']}(S, t)")
        w("")
    # controllers
    for g in model["grafcets"]:
        w(f"def grafcet_{g['id']}(S, C):")
        w(f"    \"\"\"Controller of {g['id']} ({g.get('idef0','')}: {g.get('name','')})\"\"\"")
        for tr in g["transitions"]:
            srcs, dsts = tr["from"], tr["to"]
            guard = " and ".join(f"S.X['{s}']" for s in srcs)
            cond = cond_to_py(tr["cond"], step_ids)
            blk = [s for s in srcs if all_steps[s][1].get("blocking")]
            if blk:
                cond = f"({cond}) and " + " and ".join(f"C.{s_}_done" for s_ in [f"s{b}" for b in blk])
            w(f"    if {guard} and ({cond}):   # {tr['id']}: {tr['cond']}")
            for s in srcs:
                w(f"        S.X['{s}'] = 0")
            for d in dsts:
                w(f"        S.activate('{d}', C.t)")
                if all_steps[d][1].get("macro"):
                    w(f"        reset_{all_steps[d][1]['macro']}(S, C.t)")
                if all_steps[d][1].get("blocking"):
                    w(f"        C.s{d}_done = False")
            w(f"        S.trace.append((round(C.t, 2), '{tr['id']}', {srcs!r}, {dsts!r}))")
            w("        return")
        w("    return")
        w("")
    # datapaths
    for g in model["grafcets"]:
        w(f"def datapath_{g['id']}(S, C, A):")
        for a in g.get("continuous", []):
            outs = ", ".join(f"C.{o}" for o in a["out"]) or "_"
            ins = ", ".join(f"C.{i}" for i in a["in"])
            w(f"    {outs} = A.{a['fn']}({ins})   # continuous ({g['id']})")
        for s in g["steps"]:
            acts = s.get("actions", [])
            if not acts and not s.get("macro") and not s.get("status"):
                continue
            w(f"    if S.X['{s['id']}']:   # step {s['id']} <- IDEF0 {s.get('idef0','-')}")
            for a in acts:
                outs = ", ".join(f"C.{o}" for o in a["out"])
                ins = ", ".join(f"C.{i}" for i in a["in"])
                if a["out"]:
                    w(f"        {outs} = A.{a['fn']}({ins})")
                else:
                    w(f"        A.{a['fn']}({ins})")
            if s.get("status"):
                w(f"        C.status = '{s['status']}'")
            if s.get("macro"):
                w(f"        datapath_{s['macro']}(S, C, A)")
                w(f"        grafcet_{s['macro']}(S, C)")
        w("    return")
        w("")
    top = model["top"]
    conc = model.get("concurrent", [])
    w("def reset_all(S, t):")
    w(f"    reset_{top}(S, t)")
    for g in conc:
        w(f"    reset_{g}(S, t)")
    w("")
    w("def tick(S, C, A):")
    w(f"    datapath_{top}(S, C, A)")
    w(f"    grafcet_{top}(S, C)")
    for g in conc:
        w(f"    datapath_{g}(S, C, A)   # concurrent supervisor: runs after the mission datapath (override rule)")
        w(f"    grafcet_{g}(S, C)")
    w("")
    w(f"MODEL_SHA = '{sha}'")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    m = json.load(open(sys.argv[1]))
    open(sys.argv[2], "w").write(synthesize(m, sys.argv[1]))
    print("synthesized", sys.argv[2])
